'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.join(__dirname,'..');
const course=JSON.parse(fs.readFileSync(path.join(root,'dist/course.json'),'utf8'));
const app=fs.readFileSync(path.join(root,'dist/app.js'),'utf8');
const context=vm.createContext({console,document:{},localStorage:{},setTimeout,clearTimeout});
vm.runInContext(app.slice(0,app.indexOf('function inline(')),context);
context.fixture=course;
vm.runInContext('course=fixture;',context);
const run=input=>{context.input=input;return JSON.parse(vm.runInContext('JSON.stringify(cleanState(input))',context));};
const id='01-01';
const old={version:1,done:[id,'99-99'],bookmarks:[id],notes:{[id]:'Моя заметка <без потерь>'},checks:{[id]:[0,1,99]},answers:{[id]:[0,2]},scores:{[id]:2},last:id,hours:8,labChecks:[1]};
const migrated=run(old);
assert.deepEqual(migrated.done,[id]);
assert.equal(migrated.notes[id],old.notes[id]);
assert.deepEqual(migrated.bookmarks,[id]);
assert.deepEqual(migrated.checks[id],[0,1]);
assert.equal(migrated.answers[id].length,course.lessons[0].quiz.length);
assert.equal(migrated.answers[id][2],null);
assert.equal(Object.hasOwn(migrated.scores,id),false,'An old two-question result must not count as passing the expanded quiz');
assert.equal(migrated.revision,2);
const answers=course.lessons[0].quiz.map(q=>q.answer);
const current=run({...old,revision:2,reviewed:[id,'99-99'],answers:{[id]:answers},scores:{[id]:0}});
assert.deepEqual(current.reviewed,[id]);
assert.equal(current.scores[id],answers.length,'Stored score is recomputed from valid complete answers');
assert.deepEqual(run(current),current,'Import/export round trip keeps revision2 state');
assert.deepEqual(run(null).done,[]);
console.log('Progress migration: legacy notes/completions preserved; expanded quizzes invalidate old scores; revision2 round trip verified.');
